import fsp from 'node:fs/promises';
import path from 'node:path';
import { CompactError, EXIT } from '../errors.mjs';
import { walk, writeJson, ensureDir } from '../util/fs.mjs';
import { readTemplate } from '../transform/build.mjs';
import { collectPublishFiles, scanForSecrets, pushFiles } from '../github/push.mjs';
import { slugify } from '../store/state.mjs';
import { loadApp, readProject, dirs } from './project.mjs';

const SERVERLESS_RUNTIME = ['core.mjs', 'pq.mjs', 'merkle.mjs', 'store.mjs', 'kv.mjs', 'serverless.mjs'];
const isRealEnv = (rel) => /(^|\/)\.env(\..+)?$/.test(rel) && !/\.(example|sample)$/.test(rel);
const NOBLE = '^0.5.0';

async function envNames(file) {
  try { return (await fsp.readFile(file, 'utf8')).split(/\r?\n/).map((l) => /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=/.exec(l)?.[1]).filter(Boolean); } catch { return []; }
}

/**
 * Build ONE repository that Vercel can deploy as-is: your Vite app at the root, the critical code under
 * compact/critical, the Compact runtime under compact/runtime, and a single serverless function
 * (api/compact/[...path].mjs) that serves the encrypted channel, the vault and your backend.
 * Nothing secret is included: runner keys, deployer keys, .env values and receipts stay out.
 */
export async function assembleVercel(app) {
  const d = dirs(app);
  const { manifest, connect } = await readProject(app);
  const out = new Map();
  const add = (p, content, mode = '100644') => out.set(p, { path: p, content: Buffer.isBuffer(content) ? content : Buffer.from(content), mode });
  const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

  const portalPkg = JSON.parse(await fsp.readFile(path.join(d.portal, 'package.json'), 'utf8'));
  const criticalPkg = JSON.parse(await fsp.readFile(path.join(d.critical, 'package.json'), 'utf8'));

  for (const rel of await walk(d.portal, { ignoreFile: isRealEnv })) {
    if (rel === 'package.json' || rel === 'src/compact/connect.json') continue;
    add(rel, await fsp.readFile(path.join(d.portal, rel)));
  }
  for (const rel of await walk(d.critical, { ignoreFile: isRealEnv })) {
    if (rel === 'package.json') continue;
    add(`compact/critical/${rel}`, await fsp.readFile(path.join(d.critical, rel)));
  }
  add('compact/critical/package.json', await fsp.readFile(path.join(d.critical, 'package.json'))); // unchanged: it is part of the signed manifest, and fixes the module type

  const deps = { ...(criticalPkg.dependencies ?? {}), ...(portalPkg.dependencies ?? {}), '@noble/post-quantum': NOBLE };
  const pkg = { ...portalPkg, dependencies: Object.fromEntries(Object.entries(deps).sort(([a], [b]) => (a < b ? -1 : 1))), engines: { node: '>=20' } };
  if (!pkg.scripts?.build) pkg.scripts = { ...(pkg.scripts ?? {}), build: 'vite build' };
  add('package.json', json(pkg));

  add('compact/manifest.json', await fsp.readFile(path.join(d.compact, 'manifest.json')));
  add('compact/manifest.sig', await fsp.readFile(path.join(d.compact, 'manifest.sig')));
  add('compact/compact.config.json', await fsp.readFile(path.join(d.compact, 'compact.config.json')));
  for (const t of SERVERLESS_RUNTIME) add(`compact/runtime/${t}`, await readTemplate(t));

  add('src/compact/connect.json', json({ ...connect, layout: 'vercel', endpoint: 'auto' }));
  add('api/compact/[...path].mjs', [
    '// Generated by Compact. One Vercel function: post-quantum channel + encrypted vault + your critical code.',
    "import { createServerlessHandler } from '../../compact/runtime/serverless.mjs';",
    'export default createServerlessHandler();',
    '',
  ].join('\n'));
  add('vercel.json', json({
    functions: { 'api/compact/**/*.mjs': { includeFiles: 'compact/**', maxDuration: 30 } },
    rewrites: [{ source: '/((?!api/).*)', destination: '/index.html' }],
  }));
  add('.gitignore', 'node_modules\ndist\n.vercel\n.env\n.env.*\n!.env.example\n');

  const appSecrets = [...new Set(await envNames(path.join(d.critical, '.env')))];
  const env = {
    required: ['COMPACT_KEYS_B64'],
    storage: ['UPSTASH_REDIS_REST_URL', 'UPSTASH_REDIS_REST_TOKEN'],
    app: appSecrets,
  };
  add('.env.example', [
    '# Set these in Vercel: Project, Settings, Environment Variables. Never commit values.',
    '# Printed by: compact keys --b64   (keep it a secret; do not expose it to the browser)',
    'COMPACT_KEYS_B64=',
    '# Added automatically when you connect the Upstash Redis integration (older projects: KV_REST_API_URL / KV_REST_API_TOKEN)',
    'UPSTASH_REDIS_REST_URL=',
    'UPSTASH_REDIS_REST_TOKEN=',
    ...(appSecrets.length ? ['# Your app\'s own secrets (names only, values are in your local critical/.env):', ...appSecrets.map((n) => `${n}=`)] : []),
    '',
  ].join('\n'));
  add('README.vercel.md', [
    `# ${app.name} on Vercel (generated by Compact)`,
    '',
    '1. Import this repository in Vercel (Add New, Project). Framework preset: Vite.',
    '2. Add the Upstash Redis integration (Storage, Marketplace). It sets the UPSTASH_REDIS_REST_* variables.',
    '3. Add the other variables from `.env.example` in Settings, Environment Variables.',
    '4. Deploy. Check `https://<your-app>.vercel.app/api/compact/health`.',
    '5. On your machine: `compact deploy --endpoint https://<your-app>.vercel.app`, then `compact commit --force`.',
    '',
    'Everything the browser talks to goes through /api/compact (encrypted). Keep this repository private.',
    '',
  ].join('\n'));
  return { files: [...out.values()], env, manifest };
}

/** Publish the whole app (portal + critical + Compact runtime) as one repository ready for Vercel. */
export async function pushProject(ctx, ref, { owner, repo, branch, isPrivate = true, message, allowSecrets = false, dryRun = false, token } = {}) {
  const { ui } = ctx;
  const app = await loadApp(ctx, ref);
  const asm = await ui.task('Assembling the single-repo Vercel app', () => assembleVercel(app));
  const findings = scanForSecrets(asm.files);
  if (findings.length && !allowSecrets) {
    throw new CompactError('E_SECRETS_IN_REPO', 'Something that looks like a secret is in the files to publish, so nothing was pushed.', {
      hint: 'Remove it. If it is a false positive, re-run with --allow-secrets.', details: findings.map((f) => `${f.file}: ${f.label}`), exitCode: EXIT.VALIDATION,
    });
  }
  if (dryRun) return { app, dryRun: true, files: asm.files.map((f) => f.path), env: asm.env };

  const gh = await ctx.github({ token });
  const prev = app.github?.layout === 'vercel' ? app.github : null;
  const target = { owner: owner ?? prev?.owner, repo: repo ?? prev?.repo ?? slugify(app.name), branch: branch ?? prev?.branch ?? 'main' };
  const res = await ui.task(`Pushing ${asm.files.length} files to GitHub`, async (t) =>
    pushFiles(gh, { ...target, files: asm.files, isPrivate, message: message ?? `Compact build of ${app.name} for Vercel`, onProgress: (n, m) => t.update(`Uploading files ${n}/${m}`) }));
  const record = { owner: res.owner, repo: res.repo, branch: res.branch, commitSha: res.commitSha, url: res.url, private: res.private ?? isPrivate, at: new Date().toISOString(), unchanged: res.unchanged, layout: 'vercel' };
  await ctx.state.upsert(app.id, (a) => ({ ...a, github: record, pushes: [...(a.pushes ?? []), record] }));

  const { d, connect } = await readProject(app);
  if (connect.layout !== 'vercel') await writeJson(d.connectFile, { ...connect, layout: 'vercel' }); // so vault/commit know where the routes are
  return { app, ...record, created: res.created, env: asm.env, fileCount: asm.files.length };
}

/** Write the same single-repo tree to a local folder (to inspect it, or run `vercel dev`). */
export async function exportProject(ctx, ref, { out, force = false } = {}) {
  const app = await loadApp(ctx, ref);
  const dest = path.resolve(ctx.cwd, out ?? `${slugify(app.name)}-vercel`);
  const exists = await fsp.readdir(dest).then((l) => l.length > 0, () => false);
  if (exists && !force) throw new CompactError('E_OUT_EXISTS', `${dest} already exists and is not empty.`, { hint: 'Choose another --out, or pass --force.', exitCode: EXIT.USAGE });
  const asm = await assembleVercel(app);
  for (const f of asm.files) {
    const p = path.join(dest, f.path);
    await ensureDir(path.dirname(p));
    await fsp.writeFile(p, f.content);
  }
  return { app, dest, files: asm.files.length, env: asm.env };
}
