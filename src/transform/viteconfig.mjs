// Make sure a Vite portal always has a Vite config that loads the React plugin.
//
// Why: Vite compiles .jsx files with the classic JSX transform unless the React plugin is configured.
// A file that uses JSX without `import React` then crashes in the browser with "React is not defined",
// React never mounts, and the page stays blank (a white screen). Compact generates vite.config.ts when
// the app has none, and overwrites an existing config that does not load a React plugin.

const CONFIG_RE = /^vite\.config\.[cm]?[jt]s$/;
const PLUGINS = ['@vitejs/plugin-react', '@vitejs/plugin-react-swc'];

const depsOf = (pkg) => ({ ...(pkg?.dependencies ?? {}), ...(pkg?.devDependencies ?? {}) });
export const isViteApp = (pkg) => !!depsOf(pkg).vite;
export const usesReact = (pkg) => { const d = depsOf(pkg); return !!(d.react || d['react-dom'] || PLUGINS.some((p) => d[p])); };
export const findViteConfig = (rootFiles) => rootFiles.find((f) => CONFIG_RE.test(f)) ?? null;

/** plugin-react 4.x supports Vite up to 6; 5.x is the line for Vite 7. */
export function pluginVersion(pkg) {
  const major = parseInt(String(depsOf(pkg).vite ?? '').replace(/^[^\d]*/, ''), 10);
  return major >= 7 ? '^5.0.0' : '^4.3.4';
}

export function viteConfigSource({ react }) {
  return [
    "import { defineConfig } from 'vite';",
    ...(react ? ["import react from '@vitejs/plugin-react';"] : []),
    '',
    '// Generated by Compact. Ensures the React plugin is loaded so JSX does not produce a blank page.',
    ...(react ? ['// Without the React plugin, JSX files that do not import React fail in the browser with',
      '// "React is not defined", and the page stays blank. This loads the plugin (automatic JSX runtime).'] : []),
    'export default defineConfig({',
    ...(react ? ['  plugins: [react()],'] : []),
    "  build: { outDir: 'dist', sourcemap: true },",
    '});',
    '',
  ].join('\n');
}

/**
 * Decide what a portal needs. `rootFiles` are the file names at the portal root; `readFile(name)` returns text.
 * Returns { write: {path, content} | null, remove: string[], pkg, notes }.
 * `pkg` is a copy with the plugin added if the generated config needs it.
 *
 * Behaviour:
 * - No vite.config.* → write vite.config.ts
 * - Existing config that already loads a React plugin → leave it alone
 * - Existing config that does NOT load a React plugin → remove the old file(s) and write a correct vite.config.ts
 *   (this is the white-screen fix for apps that ship a bare vite.config)
 */
export async function planViteConfig({ rootFiles, pkg, readFile }) {
  const notes = [];
  if (!isViteApp(pkg)) return { write: null, remove: [], pkg, notes };
  const react = usesReact(pkg);
  const existing = findViteConfig(rootFiles);

  if (existing) {
    if (react) {
      const text = await readFile(existing).catch(() => '');
      if (PLUGINS.some((p) => text.includes(p))) {
        // Config is fine – do not touch it
        return { write: null, remove: [], pkg, notes };
      }
      // Missing React plugin → overwrite (white-screen case)
      notes.push(`overwrote ${existing} (it did not load a React plugin; this was causing a blank page)`);
    } else {
      // Non-React Vite app with a config – leave it
      return { write: null, remove: [], pkg, notes };
    }
  } else {
    notes.push('generated vite.config.ts (your app had none), so React/JSX compiles correctly and the page does not render blank');
  }

  const next = structuredClone(pkg);
  if (react && !PLUGINS.some((p) => depsOf(next)[p])) {
    next.devDependencies = { ...(next.devDependencies ?? {}), '@vitejs/plugin-react': pluginVersion(next) };
    notes.push(`added @vitejs/plugin-react to devDependencies (${next.devDependencies['@vitejs/plugin-react']})`);
  }

  // Collect every vite.config.* so we don't leave a stale .js next to the new .ts
  const remove = rootFiles.filter((f) => CONFIG_RE.test(f));

  return { write: { path: 'vite.config.ts', content: viteConfigSource({ react }) }, remove, pkg: next, notes };
}
